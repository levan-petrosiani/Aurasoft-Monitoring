"""Rows of the store's tables. Field names are the column names, so rows load with psycopg's class_row."""

from dataclasses import dataclass, field
from datetime import datetime
from uuid import UUID


@dataclass
class RunRow:
    """One execution of scenarios against one bank (CLI, portal or imported from a report folder)."""
    id: str                      # the run folder name
    source: str                  # cli | portal
    status: str                  # Queued | Running | Completed | Failed | Cancelled
    bank_bic: str
    bank_name: str | None = None
    xs2a_url: str | None = None
    tpp_id: str | None = None
    tool_version: str | None = None
    created_utc: datetime | None = None
    started_utc: datetime | None = None
    finished_utc: datetime | None = None
    passed: int = 0
    failed: int = 0
    errors: int = 0
    blocked: int = 0
    skipped: int = 0
    pass_rate: float = 0
    suites: list[str] = field(default_factory=list)
    error: str | None = None
    report_directory: str | None = None
    options_json: dict | None = None
    scenarios: list["ScenarioRow"] = field(default_factory=list)


@dataclass
class ScenarioRow:
    run_id: str
    ordinal: int
    scenario_id: str
    title: str
    suite: str
    severity: str
    outcome: str
    spec_ref: str | None = None
    origin: str | None = None
    reason: str | None = None
    duration_ms: int = 0
    id: int | None = None
    steps: list["StepRow"] = field(default_factory=list)


@dataclass
class StepRow:
    run_id: str
    ordinal: int
    is_cleanup: bool
    name: str
    kind: str
    outcome: str
    failures: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    info: list[str] = field(default_factory=list)
    duration_ms: int = 0
    id: int | None = None
    scenario_result_id: int | None = None
    exchanges: list["ExchangeRow"] = field(default_factory=list)


@dataclass
class ExchangeRow:
    """One HTTP request/response. Secrets are masked and bodies are size-capped before they are stored."""
    run_id: str
    ordinal: int
    method: str
    url: str
    status_code: int | None = None
    duration_ms: int = 0
    error: str | None = None
    started_utc: datetime | None = None
    request_headers: list = field(default_factory=list)   # [[name, value], ...]
    request_body: str | None = None
    response_headers: list = field(default_factory=list)
    response_body: str | None = None
    truncated: bool = False
    id: int | None = None
    step_result_id: int | None = None


@dataclass
class RunSummaryRow:
    """An AI summary (triage) of a run. Regenerating adds a new row; the newest one is shown."""
    id: UUID
    run_id: str
    created_utc: datetime
    provider: str
    model: str
    status: str                  # ok | unstructured | failed
    summary_json: dict | None = None
    text: str | None = None
    validation_notes: list[str] = field(default_factory=list)
    ai_call_id: UUID | None = None
    triggered_by: str | None = None
    duration_ms: int = 0


@dataclass
class StandardDocumentRow:
    id: str                      # BG-IG, GE-XS2A
    version: str
    title: str
    language: str                # en | ka
    url: str
    sha256: str
    publisher: str | None = None
    license: str | None = None
    ingested_utc: datetime | None = None
    clause_count: int = 0


@dataclass
class ClauseRow:
    """One numbered section of a standard. `search` (tsvector) is generated by PostgreSQL."""
    standard: str
    version: str
    number: str
    title: str
    text: str
    level: int
    ord: int
    language: str
    key: str                     # BG-IG:1.3.16:6.3.1.2
    parent: str | None = None
    page: int | None = None
    id: int | None = None
    embedding: object | None = None


@dataclass
class RuleRow:
    """One checkable requirement taken from a clause; only a review sets approved/rejected."""
    id: str                      # BG-CON-001
    status: str                  # draft | approved | rejected | retired | invalid
    title: str
    level: str                   # MUST | SHOULD | MAY
    service: str                 # AIS | PIS | COMMON
    area: str
    requirement: str
    standard: str
    version: str
    clause_number: str
    clause_key: str
    quote: str
    drafted_by: str
    created_utc: datetime
    updated_utc: datetime
    quote_english: str | None = None
    operation: str | None = None
    check_json: dict | None = None
    notes: str | None = None
    check_notes: list[str] = field(default_factory=list)
    similar_to: str | None = None
    model: str | None = None
    ai_call_id: UUID | None = None
    reviewed_by: str | None = None
    reviewed_utc: datetime | None = None
    review_note: str | None = None
    scenarios: list[str] = field(default_factory=list)
    embedding: object | None = None


@dataclass
class RuleReviewRow:
    rule_id: str
    time_utc: datetime
    reviewer: str
    action: str                  # drafted | edited | approved | rejected | reopened | retired
    note: str | None = None
    before: dict | None = None
    after: dict | None = None
    id: int | None = None


@dataclass
class AiCallRow:
    """Audit record of one model call: what was sent (masked), what came back, cost drivers, who asked."""
    id: UUID
    time_utc: datetime
    feature: str
    provider: str
    model: str
    prompt_sha256: str
    request: list | dict
    duration_ms: int
    succeeded: bool
    run_id: str | None = None
    triggered_by: str | None = None
    response: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    error: str | None = None


@dataclass
class ScenarioDraftRow:
    """A test scenario drafted by AI from an approved rule; becomes a file in scenarios/ only when a person approves it."""
    id: UUID
    rule_id: str
    scenario_id: str
    suite: str
    title: str
    yaml: str
    status: str                  # draft | failed | approved | rejected
    attempts: int
    drafted_by: str
    created_utc: datetime
    updated_utc: datetime
    check_notes: list[str] = field(default_factory=list)
    dry_run_outcome: str | None = None
    dry_run: dict | None = None
    mock_gap: str | None = None
    model: str | None = None
    ai_call_ids: list[UUID] = field(default_factory=list)
    reviewed_by: str | None = None
    reviewed_utc: datetime | None = None
    review_note: str | None = None
    file_path: str | None = None


@dataclass
class AgentQuestionRow:
    """A question to the ask-agent, its answer, the tool calls behind it and the citation check."""
    id: UUID
    asked_utc: datetime
    question: str
    status: str                  # ok | unverified | failed
    provider: str
    model: str
    asked_by: str | None = None
    answer: str | None = None
    tool_calls: list = field(default_factory=list)
    citation_notes: list[str] = field(default_factory=list)
    ai_call_ids: list[UUID] = field(default_factory=list)
    error: str | None = None
    duration_ms: int = 0
