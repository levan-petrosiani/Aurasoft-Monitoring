    level integer NOT NULL,
    parent text,
    ord integer NOT NULL,
    page integer,
    language text NOT NULL,
    key text NOT NULL,
    embedding public.vector(1024),
    search tsvector GENERATED ALWAYS AS (
CASE
    WHEN (language = 'en'::text) THEN to_tsvector('english'::regconfig, ((((COALESCE(number, ''::text) || ' '::text) || COALESCE(title, ''::text)) || ' '::text) || COALESCE(text, ''::text)))
    ELSE to_tsvector('simple'::regconfig, ((((COALESCE(number, ''::text) || ' '::text) || COALESCE(title, ''::text)) || ' '::text) || COALESCE(text, ''::text)))
END) STORED
);

